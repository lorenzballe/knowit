#!/usr/bin/env python3
"""Turns `remote/` into what the app reads.

    python3 tool/remote/bundle.py           # write both copies
    python3 tool/remote/bundle.py --check   # fail if either copy is stale

The remote document is everything about the app that can change without a
release: the update gate and the switches (`remote/app.json`), words that
replace the build's own (`remote/strings/<language>.json`), the shelves of
Explore (`remote/explore.json`) and how cards look (`remote/looks.json`).
Each is checked by its own part of `tool/remote/check.py` first; nothing is
written while any of them fails.

Like the bank, the document is written twice from the same bytes: baked
into the build as `lib/remote/embedded_config.dart`, so a phone that has
never been online has the app the build shipped with, and published as
`web/remote/config.json`, which the deploy copies to the site beside a small
`version.json` naming it. A document is named by the hash of what it holds,
so two documents with the same contents are the same document, and a check
needs no clock.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(HERE))

import check  # noqa: E402

EMBEDDED = ROOT / "lib" / "remote" / "embedded_config.dart"
PUBLISHED = ROOT / "web" / "remote" / "config.json"
VERSION = ROOT / "web" / "remote" / "version.json"

SCHEMA = 1


def build(parts: dict) -> dict:
    """The document: the schema, the parts in a fixed order, and the hash of
    them all."""
    body = {"schema": SCHEMA}
    for name in check.PARTS:
        body[name] = parts.get(name)
    canonical = json.dumps(body, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    digest = hashlib.sha256(canonical.encode("utf-8")).hexdigest()[:16]
    return {"schema": SCHEMA, "hash": digest, **{k: v for k, v in body.items() if k != "schema"}}


def version_note(doc: dict) -> str:
    return json.dumps({"schema": doc["schema"], "hash": doc["hash"]}) + "\n"


def render_dart(text: str) -> str:
    return (
        "// GENERATED by tool/remote/bundle.py from remote/. Do not edit: change\n"
        "// the sources and run the bundler. CI checks this is current.\n"
        "\n"
        "/// The remote document the app ships with, as the JSON the site also\n"
        "/// serves. Parsed once, by Remote.embedded.\n"
        "const String kEmbeddedRemote = r'''\n" + text + "''';\n"
    )


def read_embedded() -> str | None:
    if not EMBEDDED.exists():
        return None
    text = EMBEDDED.read_text(encoding="utf-8")
    start, end = text.find("r'''\n"), text.rfind("''';")
    if start < 0 or end < 0:
        return None
    return text[start + 5:end]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="only report whether the copies are current")
    args = ap.parse_args(argv)

    parts, problems = check.load_and_check()
    if problems:
        for p in problems:
            print(p)
        print("the remote document does not pass; nothing written")
        return 1

    doc = build(parts)
    text = json.dumps(doc, ensure_ascii=False, indent=1) + "\n"
    if "'''" in text:
        print("the document holds ''' somewhere, which the Dart copy cannot carry")
        return 1

    embedded_ok = read_embedded() == text
    published_ok = PUBLISHED.exists() and PUBLISHED.read_text(encoding="utf-8") == text
    version_ok = VERSION.exists() and VERSION.read_text(encoding="utf-8") == version_note(doc)
    if args.check:
        if embedded_ok and published_ok and version_ok:
            print(f"remote document {doc['hash']}: both copies current")
            return 0
        print("stale:" + ("" if embedded_ok else " lib/remote/embedded_config.dart")
              + ("" if published_ok else " web/remote/config.json")
              + ("" if version_ok else " web/remote/version.json"))
        print("run python3 tool/remote/bundle.py")
        return 1

    if embedded_ok and published_ok and version_ok:
        print(f"remote document {doc['hash']}: nothing to do")
        return 0
    EMBEDDED.parent.mkdir(parents=True, exist_ok=True)
    PUBLISHED.parent.mkdir(parents=True, exist_ok=True)
    EMBEDDED.write_text(render_dart(text), encoding="utf-8")
    PUBLISHED.write_text(text, encoding="utf-8")
    VERSION.write_text(version_note(doc), encoding="utf-8")
    print(f"wrote remote document {doc['hash']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
