/// What each theme is called in the languages the app speaks besides
/// English.
///
/// [Genre.label] is a theme's English name and the key it is filed and
/// matched under; these are only how it is shown. They are keyed by
/// [Genre.id], so a theme added with no name here yet is shown in English
/// rather than under another theme's name.
library;

import '../l10n/l10n.dart';
import '../models/pill.dart';
import 'genres.dart';
import 'strand_names.dart';

/// [genre]'s name in [language] (`it`, `de`, …): its English name when this
/// build has none in that language.
String themeName(Genre genre, String language) =>
    kThemeNames[language]?[genre.id] ?? genre.label;

/// The language [l] speaks, as `it` or `de`: its locale without the region.
String languageOf(AppLocalizations l) =>
    l.localeName.split(RegExp('[_-]')).first;

/// Themes by name, in the reader's language.
extension ThemeNames on AppLocalizations {
  /// [genre]'s name in this language.
  String themeOf(Genre genre) => themeName(genre, languageOf(this));

  /// The name of the theme filed under [id] in this language, or [orElse]
  /// when no theme is.
  String themeById(String id, {String orElse = ''}) {
    final Genre? genre = genreById(id);
    return genre == null ? orElse : themeOf(genre);
  }

  /// Where [card] sits, by name: its theme, or its subject when it is filed
  /// under no theme.
  String themeOfCard(Pill card) =>
      themeById(card.genre, orElse: subjectOf(card.topic));

  /// [strand]'s name in this language.
  String strandOf(Strand strand) => strandName(strand.id) ?? strand.label;

  /// The name of the strand filed under [id] in this language, or null when
  /// this build has none in it.
  String? strandName(String id) => kStrandNames[languageOf(this)]?[id];
}

