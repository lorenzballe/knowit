Pill _p(
  String id,
  String topicKey,
  String q,
  String a,
  String bar,
  String src,
) {
  final t = kTopics[topicKey]!;
  return Pill(
    id: id,
    topic: t.name,
    color: t.color,
    ink: t.ink,
    tint: t.tint,
    question: q,
    answer: a,
    barMove: bar,
    source: src,
  );
}

/// Builds a puzzle card: the reader commits to one of [choices] before the
/// card turns over. [trap] names the answer most people reach for first.
Pill _q(
  String id,
  String topicKey,
  String q,
  List<String> choices,
  int correct,
  String trap,
  String a,
  String bar,
  String src, {
  String simply = '',
  Principle principle = Principle.none,
}) {
  final t = kTopics[topicKey]!;
  return Pill(
    id: id,
    topic: t.name,
    color: t.color,
    ink: t.ink,
    tint: t.tint,
    question: q,
    answer: a,
    barMove: bar,
    source: src,
    challenge: PickOne(options: choices, correct: correct),
    trap: trap,
    simply: simply,
    difficulty: Difficulty.medium,
    principle: principle,
  );
}

/// Builds a competition-style problem: the reader works out a number and
/// types it. [steps] is the solution, one move per line.
Pill _n(
  String id,
  String topicKey,
  String q,
  num answer,
  String unit,
  String hint,
  List<String> steps,
  String bar,
  String src, {
  Difficulty difficulty = Difficulty.medium,
  String simply = '',
  Principle principle = Principle.computation,
}) {
  final t = kTopics[topicKey]!;
  return Pill(
    id: id,
    topic: t.name,
    color: t.color,
    ink: t.ink,
    tint: t.tint,
    question: q,
    answer: steps.isEmpty ? '' : steps.last,
    barMove: bar,
    source: src,
    simply: simply,
    challenge: TypeNumber(answer: answer, unit: unit),
    hint: hint,
    steps: steps,
    difficulty: difficulty,
    principle: principle,
  );
}

