    id: id,
    topic: t.name,
    color: t.color,
    ink: t.ink,
    tint: t.tint,
    question: claim,
    answer: yourCase,
    barMove: bar,
    source: src,
    challenge: TakeASide(positions: positions),
    counterpoint: counterpoint,
    difficulty: Difficulty.medium,
  );
}

